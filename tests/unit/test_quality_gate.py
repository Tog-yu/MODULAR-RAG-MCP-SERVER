class TestValidCharRatio:
    def test_pure_ascii_text(self, gate):
        ratio = gate._compute_valid_char_ratio("Hello World 123")
        assert ratio == 1.0

    def test_chinese_text(self, gate):
        ratio = gate._compute_valid_char_ratio("检索增强生成")
        assert ratio == 1.0

    def test_mixed_with_garbage(self, gate):
        # 5 valid + 5 invalid non-whitespace chars -> 0.5
        text = "Hello" + "«»§¶†"
        ratio = gate._compute_valid_char_ratio(text)
        assert ratio == pytest.approx(0.5)

    def test_whitespace_ignored(self, gate):
        ratio = gate._compute_valid_char_ratio("H e l l o\t\n 1 2 3 ")
        assert ratio == 1.0

    def test_empty_text_returns_one(self, gate):
        # Empty -> 1.0 so text_density is the deciding metric instead.
        assert gate._compute_valid_char_ratio("") == 1.0


class TestTextDensity:
    def test_all_pages_text_bearing(self, gate):
        pages = ["Hello World 123 " * 10] * 3
        assert gate._compute_text_density(pages) == 1.0

    def test_no_pages_text_bearing(self, gate):
        pages = ["", " ", "«»§¶"]  # below min_chars_per_page
        assert gate._compute_text_density(pages) == 0.0

    def test_partial_density(self, gate):
        good = "Hello World 123 " * 10  # >= 50 valid chars
        bad = "hi"  # < min_chars_per_page (50)
        density = gate._compute_text_density([good, bad, bad, good])
        assert density == pytest.approx(0.5)

    def test_empty_page_list(self, gate):
        assert gate._compute_text_density([]) == 0.0


