class TestThresholds:
    def test_ratio_exactly_at_threshold_passes(self):
        # 80 valid + 20 invalid = exactly 0.80 -> >= passes
        text = "A" * 80 + "«" * 20
        cfg = QualityGateConfig(min_valid_char_ratio=0.80)
        gate = DocumentQualityGate(cfg)
        assert gate._compute_valid_char_ratio(text) == pytest.approx(0.80)
        # Direct threshold comparison mirrors gate.check logic
        assert gate._compute_valid_char_ratio(text) >= cfg.min_valid_char_ratio

    def test_density_exactly_at_threshold_passes(self):
        good = "Hello World 123 " * 10
        cfg = QualityGateConfig(min_text_density=0.50)
        gate = DocumentQualityGate(cfg)
        # 2/4 pages text-bearing = 0.50 -> >= passes
        assert gate._compute_text_density([good, "", good, ""]) >= cfg.min_text_density

    def test_custom_strict_thresholds_reject_healthy(self, healthy_pdf):
        cfg = QualityGateConfig(min_valid_char_ratio=1.01)  # impossible
        gate = DocumentQualityGate(cfg)
        result = gate.check(healthy_pdf)
        assert result.passed is False


