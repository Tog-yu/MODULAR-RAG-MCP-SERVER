class TestPipelineIntegration:
    def _make_pipeline(self, tmp_path, monkeypatch, gate_result=None):
        """Build a minimal IngestionPipeline-like object for run() testing.

        We construct a real IngestionPipeline but patch every heavy component
        so run() can be exercised end-to-end without LLM/Chroma/Embedding.
        """
        from src.core.settings import Settings
        from src.ingestion.pipeline import IngestionPipeline

        data = _minimal_settings_dict({"quality_gate": {"enabled": True}})
        data["ingestion"] = {
            "chunk_size": 100, "chunk_overlap": 0, "splitter": "recursive", "batch_size": 10,
        }
        data["vector_store"]["persist_directory"] = str(tmp_path / "chroma")
        settings = Settings.from_dict(data)

        # Patch all heavy component constructors before instantiation.
        from src.ingestion import pipeline as pl
        from src.libs.loader import loader_factory as lf
        from src.libs.embedding import embedding_factory as ef
        from src.libs.vector_store import vector_store_factory as vf
        from src.ingestion.chunking import document_chunker as dc
        from src.ingestion.transform import chunk_refiner as cr
        from src.ingestion.transform import metadata_enricher as me
        from src.ingestion.transform import image_captioner as ic
        from src.ingestion.embedding import dense_encoder as de
        from src.ingestion.storage import bm25_indexer as bi
        from src.ingestion.storage import vector_upserter as vu
        from src.ingestion.storage import image_storage as ims

        monkeypatch.setattr(pl, "SQLiteIntegrityChecker", lambda **kw: _FakeIntegrity())
        monkeypatch.setattr(pl, "DocumentChunker", lambda s: _FakeChunker())
        monkeypatch.setattr(pl, "ChunkRefiner", lambda s: _FakeRefiner())
        monkeypatch.setattr(pl, "MetadataEnricher", lambda s: _FakeEnricher())
        monkeypatch.setattr(pl, "ImageCaptioner", lambda s: _FakeCaptioner())
        monkeypatch.setattr(pl, "VectorUpserter", lambda s, collection_name=None: _FakeUpserter())
        monkeypatch.setattr(pl, "BM25Indexer", lambda index_dir=None: _FakeBM25())
        monkeypatch.setattr(pl, "ImageStorage", lambda **kw: _FakeImageStore())
        monkeypatch.setattr(ef.EmbeddingFactory, "create", lambda s: _FakeEmbedding())
        # BatchProcessor is constructed with keyword args in the pipeline.
        monkeypatch.setattr(pl, "BatchProcessor", lambda **kw: _FakeBatchProcessor())
        # Settings.embedding.provider is accessed for logging only.
        if gate_result is not None:
            fake_gate = _FakeGate(gate_result)
            monkeypatch.setattr(pl, "DocumentQualityGate", lambda cfg=None: fake_gate)
        else:
            monkeypatch.setattr(pl, "DocumentQualityGate", lambda cfg=None: DocumentQualityGate(cfg))

        return IngestionPipeline(settings, collection="test_qg", force=True)

    def test_low_quality_pdf_rejected_before_load(self, tmp_path, monkeypatch, low_quality_pdf):
        from src.ingestion.pipeline import IngestionPipeline

        pipeline = self._make_pipeline(tmp_path, monkeypatch)
        result = pipeline.run(str(low_quality_pdf))

        assert result.success is False
        assert result.rejected is True
        assert QUALITY_REJECT_MESSAGE in result.error
        assert "quality_check" in result.stages
        # Loader must NOT have been invoked (no load stage recorded)
        assert "loading" not in result.stages
        # Integrity history recorded the rejection
        assert pipeline.integrity_checker.calls == [("mark_failed", "quality_rejected")]
        pipeline.close()

    def test_healthy_pdf_passes_gate_and_reaches_load(self, tmp_path, monkeypatch, healthy_pdf):
        pipeline = self._make_pipeline(tmp_path, monkeypatch)
        result = pipeline.run(str(healthy_pdf))

        assert result.rejected is False
        assert result.stages["quality_check"]["passed"] is True
        # Loading stage recorded -> gate did not block the healthy doc
        assert "loading" in result.stages
        pipeline.close()

    def test_gate_rejection_uses_fake_gate_result(self, tmp_path, monkeypatch, healthy_pdf):
        """Even a healthy doc is rejected when the gate says no (wiring check)."""
        from src.libs.loader.quality_gate import QualityCheckResult

        failing = QualityCheckResult(passed=False, reason="forced rejection")
        pipeline = self._make_pipeline(tmp_path, monkeypatch, gate_result=failing)
        result = pipeline.run(str(healthy_pdf))

        assert result.rejected is True
        assert result.error == "forced rejection"
        pipeline.close()


