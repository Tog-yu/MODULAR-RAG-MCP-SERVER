class TestDispatch:
    def test_pdf_registered_by_default(self):
        assert ".pdf" in DEFAULT_QUALITY_EXTENSIONS

    def test_non_registered_format_passes(self, tmp_path):
        md = tmp_path / "doc.md"
        md.write_text("# anything")
        gate = DocumentQualityGate(QualityGateConfig(extensions=[".pdf"]))
        result = gate.check(md)
        assert result.passed is True
        assert result.sampled_pages == 0

    def test_disabled_gate_passes_anything(self, tmp_path):
        pdf = tmp_path / "bad.pdf"
        pdf.write_bytes(b"not really a pdf")
        gate = DocumentQualityGate(QualityGateConfig(enabled=False))
        result = gate.check(pdf)
        assert result.passed is True

    def test_applies_to_case_insensitive(self):
        cfg = QualityGateConfig()
        assert cfg.applies_to("A/B/report.PDF") is True
        assert cfg.applies_to("A/B/report.txt") is False

    def test_missing_file_rejected(self, tmp_path):
        gate = DocumentQualityGate()
        result = gate.check(tmp_path / "ghost.pdf")
        assert result.passed is False
        assert result.reason is not None and QUALITY_REJECT_MESSAGE in result.reason

    def test_corrupt_pdf_rejected(self, tmp_path):
        pdf = tmp_path / "corrupt.pdf"
        pdf.write_bytes(b"%PDF-1.4 broken content")
        gate = DocumentQualityGate()
        result = gate.check(pdf)
        assert result.passed is False
        assert result.reason is not None and QUALITY_REJECT_MESSAGE in result.reason


